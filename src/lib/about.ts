/** Texte par défaut de la page « À propos » quand l'admin n'en a pas saisi. */
export function defaultAboutText(name: string) {
  return `## Le projet

Bonjour ! Je m'appelle ${name} et j'habite Saint-Charles-de-Drummond. J'ai lancé ma petite entreprise de collecte de cannettes consignées pour financer mes projets, en commençant par une trottinette électrique.

Plutôt que de vous déplacer au dépanneur, je passe chercher vos cannettes directement chez vous, la journée qui vous convient. C'est gratuit, simple, et ça évite que les cannettes finissent au recyclage sans consigne.

## Quoi mettre dans le sac

- Canettes d'aluminium consignées (bière, boissons gazeuses, eau pétillante, jus, etc.)
- Idéalement vidées et rincées rapidement
- Dans un sac fermé, laissé près de l'entrée le jour de la collecte

## Merci !

Chaque cannette compte. Merci de m'encourager dans ce projet 💚`;
}
